-- 《未備份》資料庫完整存檔產生器（只讀，不會改任何東西）
-- 在 Supabase → SQL Editor 貼上執行，結果只有一格（schema_sql）。把那一格的內容整段複製給 Claude，
-- 存成 supabase/schema_YYYY-MM-DD.sql，就是當下資料庫的完整樣子。
--
-- 包含 public schema 的：資料表與欄位、預設值、限制（主鍵／唯一／檢查／外鍵）、索引、
-- RLS 開關與所有政策、函式、觸發器（含 auth.users 上呼叫 public 函式的觸發器）、事件觸發器、
-- anon／authenticated 的資料表、欄位與函式權限。
-- 不包含資料本身（會員、留言、私訊內容都不會出現）。

WITH
tbl AS (
  SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
),
cols AS (
  SELECT t.relname,
         string_agg(
           '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
           || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                 WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
           || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                   WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END
           || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
           E',\n' ORDER BY a.attnum) AS body
  FROM tbl t
  JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
  LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  GROUP BY t.relname
),
parts AS (
  -- 1. 資料表
  SELECT 10 AS sec, t.relname AS k, 'CREATE TABLE public.' || quote_ident(t.relname) || E' (\n' || c.body || E'\n);' AS s
  FROM tbl t JOIN cols c USING (relname)

  -- 2. 限制：主鍵、唯一、檢查先，外鍵最後
  UNION ALL
  SELECT CASE WHEN con.contype = 'f' THEN 30 ELSE 20 END, t.relname || '.' || con.conname,
         'ALTER TABLE public.' || quote_ident(t.relname) || ' ADD CONSTRAINT ' || quote_ident(con.conname)
         || ' ' || pg_get_constraintdef(con.oid) || ';'
  FROM tbl t JOIN pg_constraint con ON con.conrelid = t.oid
  WHERE con.contype IN ('p', 'u', 'c', 'f', 'x')

  -- 3. 索引（不含限制自帶的）
  UNION ALL
  SELECT 40, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  FROM tbl t JOIN pg_index i ON i.indrelid = t.oid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.indexrelid)

  -- 4. 函式（不含擴充套件帶進來的）
  UNION ALL
  SELECT 50, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend dp WHERE dp.objid = p.oid AND dp.deptype = 'e')

  -- 5. 觸發器：public 資料表上的，以及任何呼叫 public 函式的（例如 auth.users 的註冊觸發器）
  UNION ALL
  SELECT 60, tg.tgrelid::regclass::text || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  FROM pg_trigger tg
  JOIN pg_class c ON c.oid = tg.tgrelid JOIN pg_namespace cn ON cn.oid = c.relnamespace
  JOIN pg_proc p ON p.oid = tg.tgfoid JOIN pg_namespace pn ON pn.oid = p.pronamespace
  WHERE NOT tg.tgisinternal AND (cn.nspname = 'public' OR pn.nspname = 'public')

  -- 5b. 事件觸發器（例如新資料表自動開 RLS 的 rls_auto_enable）
  UNION ALL
  SELECT 65, e.evtname,
         'CREATE EVENT TRIGGER ' || quote_ident(e.evtname) || ' ON ' || e.evtevent
         || coalesce(E'\n  WHEN TAG IN (' || (SELECT string_agg(quote_literal(x), ', ') FROM unnest(e.evttags) x) || ')', '')
         || E'\n  EXECUTE FUNCTION public.' || quote_ident(p.proname) || '();'
         || CASE e.evtenabled WHEN 'D' THEN E'\nALTER EVENT TRIGGER ' || quote_ident(e.evtname) || ' DISABLE;' ELSE '' END
  FROM pg_event_trigger e JOIN pg_proc p ON p.oid = e.evtfoid JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'

  -- 6. RLS 開關
  UNION ALL
  SELECT 70, relname,
         'ALTER TABLE public.' || quote_ident(relname) || ' ENABLE ROW LEVEL SECURITY;'
         || CASE WHEN relforcerowsecurity THEN E'\nALTER TABLE public.' || quote_ident(relname) || ' FORCE ROW LEVEL SECURITY;' ELSE '' END
  FROM tbl WHERE relrowsecurity

  -- 7. RLS 政策
  UNION ALL
  SELECT 80, tablename || '.' || policyname,
         'CREATE POLICY ' || quote_ident(policyname) || ' ON public.' || quote_ident(tablename)
         || ' AS ' || permissive || ' FOR ' || cmd
         || ' TO ' || array_to_string(roles, ', ')
         || CASE WHEN qual IS NOT NULL THEN E'\n  USING (' || qual || ')' ELSE '' END
         || CASE WHEN with_check IS NOT NULL THEN E'\n  WITH CHECK (' || with_check || ')' ELSE '' END || ';'
  FROM pg_policies WHERE schemaname = 'public'

  -- 8. 資料表權限（先全部收回，再列出實際有的）
  UNION ALL
  SELECT 90, relname || '.0', 'REVOKE ALL ON public.' || quote_ident(relname) || ' FROM anon, authenticated;'
  FROM tbl
  UNION ALL
  SELECT 90, table_name || '.1.' || grantee,
         'GRANT ' || string_agg(privilege_type, ', ' ORDER BY privilege_type)
         || ' ON public.' || quote_ident(table_name) || ' TO ' || grantee || ';'
  FROM information_schema.role_table_grants
  WHERE table_schema = 'public' AND grantee IN ('anon', 'authenticated')
  GROUP BY table_name, grantee

  -- 9. 欄位權限（只列沒有整張表權限、單獨開給欄位的）
  UNION ALL
  SELECT 90, cp.table_name || '.2.' || cp.grantee || '.' || cp.privilege_type,
         'GRANT ' || cp.privilege_type || ' (' || string_agg(quote_ident(cp.column_name), ', ' ORDER BY cp.column_name)
         || ') ON public.' || quote_ident(cp.table_name) || ' TO ' || cp.grantee || ';'
  FROM information_schema.column_privileges cp
  WHERE cp.table_schema = 'public' AND cp.grantee IN ('anon', 'authenticated')
    AND NOT EXISTS (SELECT 1 FROM information_schema.role_table_grants g
                    WHERE g.table_schema = 'public' AND g.table_name = cp.table_name
                      AND g.grantee = cp.grantee AND g.privilege_type = cp.privilege_type)
  GROUP BY cp.table_name, cp.grantee, cp.privilege_type

  -- 10. 函式權限（先全部收回，再列出實際有的）
  UNION ALL
  SELECT 95, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ').0',
         'REVOKE ALL ON FUNCTION public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') FROM PUBLIC, anon, authenticated;'
         || coalesce((
              SELECT E'\nGRANT EXECUTE ON FUNCTION public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') TO '
                     || string_agg(CASE WHEN x.grantee = 0 THEN 'PUBLIC' ELSE r.rolname END, ', ' ORDER BY 1) || ';'
              FROM aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
              LEFT JOIN pg_roles r ON r.oid = x.grantee
              WHERE x.privilege_type = 'EXECUTE' AND (x.grantee = 0 OR r.rolname IN ('anon', 'authenticated'))
            ), '')
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
    AND NOT EXISTS (SELECT 1 FROM pg_depend dp WHERE dp.objid = p.oid AND dp.deptype = 'e')
)
SELECT
  '-- 《未備份》資料庫完整存檔（public schema）' || E'\n'
  || '-- 產生時間：' || to_char(now() AT TIME ZONE 'Asia/Taipei', 'YYYY-MM-DD HH24:MI') || '（台北）' || E'\n'
  || '-- 由 supabase/export_schema.sql 從實際資料庫產生。只有結構與權限，沒有資料。' || E'\n'
  || '-- 順序：資料表 → 限制 → 索引 → 函式 → 觸發器 → 事件觸發器 → RLS → 政策 → 權限；在全新的 Supabase 專案可整段執行重建。' || E'\n\n'
  || 'BEGIN;' || E'\n\n'
  || string_agg(
       s,
       E'\n\n' ORDER BY sec, k)
  || E'\n\nCOMMIT;' || E'\n'
  AS schema_sql
FROM parts;
